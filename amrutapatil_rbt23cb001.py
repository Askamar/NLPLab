# 2. Rule-Based Stemming for Hindi
# Hindi is highly inflectional. Here is a custom implementation of a common Hindi stemmer
# that strips common plural/case inflections like 'ियाँ', 'ए', 'ओं'.
def stem_hindi_word(word):
    suffixes = [
        'ाओं', 'िए', 'ीय', 'ाएं', 'ाओ', 'िओं', 'ियाँ', 'ियों',
        'कर', 'ा', 'ी', 'े', 'ू', 'ो', 'ं', 'त'
    ]
    for suffix in suffixes:
        if word.endswith(suffix):
            # Return the base stem
            return word[:-len(suffix)]
    return word

